// Snapshot AE's player balance — players/classes.sval and every skill file a
// class lists — into src/generator/players/stock.generated.ts, so the Players
// tab can show stock values and the generator can name the lines to patch
// without the game installed.
//
//   node scripts/run-ts.mjs scripts/scan-ae-players.ts           # rewrite
//   node scripts/run-ts.mjs scripts/scan-ae-players.ts --check   # exit 1 if stale
//
// Set HWAE_ROOT to point at another install.
import fs from 'node:fs'
import path from 'node:path'
import {
  COMBO_BUFFS_PATH,
  LIGHTNING_BOLT_PATH,
  POWER_SHOP_PATH,
  SHOP_CONSTANTS_PATH,
  parseClasses,
  parseExtras,
  parseShopPrices,
  parseSkillFile
} from '../src/generator/players/parse'
import type { PlayerStock } from '../src/generator/players/model'

const root = process.env.HWAE_ROOT ?? 'D:/Program Files (x86)/Steam/steamapps/common/Hammerwatch Anniversary Edition'
const dirs = fs.existsSync(root) ? fs.readdirSync(root).filter((d) => /^unpacked_assets_\d+$/.test(d)) : []
dirs.sort((a, b) => Number(b.split('_').pop()) - Number(a.split('_').pop()))
if (dirs.length === 0) {
  console.error('AE unpacked assets not found; set HWAE_ROOT')
  process.exit(1)
}
const assets = path.join(root, dirs[0])
const read = (rel: string): string => fs.readFileSync(path.join(assets, rel), 'utf8')
const readBuffs = (rel: string): string | undefined => (fs.existsSync(path.join(assets, rel)) ? read(rel) : undefined)

const classes = parseClasses(read('players/classes.sval'))
const paths: string[] = []
for (const c of classes) for (const s of c.skills) if (!paths.includes(s.path)) paths.push(s.path)
const stock: PlayerStock = {
  classes,
  skills: paths.map((p) => parseSkillFile(p, read(p), readBuffs)),
  shop: parseShopPrices(read(POWER_SHOP_PATH), read(SHOP_CONSTANTS_PATH)),
  extras: parseExtras(read(COMBO_BUFFS_PATH), read(LIGHTNING_BOLT_PATH))
}

const body = [
  '// GENERATED by scripts/scan-ae-players.ts from a Hammerwatch Anniversary Edition',
  `// install (${dirs[0]}). Do not edit by hand — rerun the script.`,
  '',
  "import type { PlayerStock } from './model'",
  '',
  `export const PLAYER_STOCK_SOURCE = ${JSON.stringify(dirs[0])}`,
  '',
  'export const PLAYER_STOCK: PlayerStock = {',
  '  classes: [',
  ...stock.classes.map((c) => `    ${JSON.stringify(c)},`),
  '  ],',
  '  skills: [',
  ...stock.skills.map((s) => `    ${JSON.stringify(s)},`),
  '  ],',
  '  shop: [',
  ...stock.shop.map((s) => `    ${JSON.stringify(s)},`),
  '  ],',
  '  extras: [',
  ...stock.extras.map((s) => `    ${JSON.stringify(s)},`),
  '  ]',
  '}',
  ''
].join('\n')

const outFile = path.join(process.cwd(), 'src', 'generator', 'players', 'stock.generated.ts')
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (current !== body) {
    console.error('stock.generated.ts is stale; rerun scripts/scan-ae-players.ts')
    process.exit(1)
  }
  console.log('player snapshot is current')
} else {
  fs.writeFileSync(outFile, body)
  const values = stock.skills.reduce(
    (n, s) =>
      n +
      s.chains.reduce(
        (m, c) =>
          m + c.tiers.reduce((k, t) => k + Object.keys(t.binds).length + Object.keys(t.params ?? {}).length + (t.cost ? 1 : 0), 0),
        0
      ),
    0
  )
  console.log(`${stock.classes.length} classes, ${stock.skills.length} skill files, ${values} skill values → ${path.relative(process.cwd(), outFile)}`)
}
