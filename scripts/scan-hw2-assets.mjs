#!/usr/bin/env node
// Snapshot the Hammerwatch 2 asset paths the generator may emit (experimental
// "Load custom" content), so tests can prove every `hw2/…` path a generated
// level references exists in HW2 — without HW2 installed. Paths only: no HW2
// file contents are stored in the repo.
//
//   node scripts/scan-hw2-assets.mjs            # rewrite src/generator/catalog/hw2Assets.generated.ts
//   node scripts/scan-hw2-assets.mjs --check    # exit 1 if the snapshot is stale
//
// Every path is stored as the scenario ships it: under the `hw2/` prefix
// (docs/discovery/hammerwatch-2-assets.md, finding 1). Scope: enemy actors (no
// NPCs), items, every doodad, every tileset with its tile size, every lighting
// environment, and the music sample names in `res/assets/sound/music.bank`.
// Set HW2_ROOT to point at another install.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const outFile = path.join(here, '..', 'src', 'generator', 'catalog', 'hw2Assets.generated.ts')
const root = process.env.HW2_ROOT ?? 'D:/Program Files (x86)/Steam/steamapps/common/Hammerwatch 2'
const dirs = fs.existsSync(root) ? fs.readdirSync(root).filter((d) => /^unpacked_assets_\d+$/.test(d)) : []
dirs.sort((a, b) => Number(b.split('_').pop()) - Number(a.split('_').pop()))
if (dirs.length === 0) {
  console.error('Hammerwatch 2 unpacked assets not found; set HW2_ROOT')
  process.exit(1)
}
const assets = path.join(root, dirs[0])

function walk(rel, out = []) {
  const abs = path.join(assets, rel)
  if (!fs.existsSync(abs)) return out
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const r = rel === '' ? e.name : `${rel}/${e.name}`
    if (e.isDirectory()) walk(r, out)
    else out.push(r)
  }
  return out
}

const P = (rel) => `hw2/${rel}`
const units = new Set()
for (const f of walk('actors')) if (f.endsWith('.unit') && !f.startsWith('actors/npcs/')) units.add(P(f))
for (const f of walk('items')) if (f.endsWith('.unit')) units.add(P(f))
for (const f of walk('doodads')) if (f.endsWith('.unit')) units.add(P(f))

const tilesets = {}
for (const f of walk('tilesets')) {
  if (!f.endsWith('.tileset')) continue
  const m = /<tileset[^>]*\bsize="(\d+)"/.exec(fs.readFileSync(path.join(assets, f), 'utf8'))
  tilesets[P(f)] = m ? Number(m[1]) : 16
}
const envs = walk('effects').filter((f) => f.endsWith('.env')).map(P)

/** Sample names of the first FSB5 block in an FMOD bank (Vorbis music: one block). */
function fsbSampleNames(file) {
  if (!fs.existsSync(file)) return []
  const buf = fs.readFileSync(file)
  const at = buf.indexOf('FSB5', 0, 'latin1')
  if (at < 0) return []
  const count = buf.readUInt32LE(at + 8)
  const shdr = buf.readUInt32LE(at + 12)
  const nameSize = buf.readUInt32LE(at + 16)
  const names = at + 60 + shdr
  const out = []
  for (let i = 0; i < count && nameSize > 0; i++) {
    const o = names + buf.readUInt32LE(names + i * 4)
    out.push(buf.toString('latin1', o, buf.indexOf(0, o)))
  }
  return out
}
const music = fsbSampleNames(path.join(root, 'res', 'assets', 'sound', 'music.bank'))

const sorted = (xs) => [...xs].sort()
const list = (xs) => JSON.stringify(sorted(xs), null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')
const body =
  '// GENERATED by scripts/scan-hw2-assets.mjs from a Hammerwatch 2 install\n' +
  `// (${path.basename(assets)}). Do not edit by hand — rerun the script.\n` +
  '// Paths only, under the `hw2/` prefix a scenario ships them at. Every `hw2/`\n' +
  '// path the generator emits must appear here (tests enforce it).\n\n' +
  `export const HW2_ASSETS_SOURCE = ${JSON.stringify(path.basename(assets))}\n\n` +
  `export const HW2_UNITS: readonly string[] = ${list(units)}\n\n` +
  `export const HW2_TILESET_SIZES: Readonly<Record<string, number>> = {\n${sorted(Object.keys(tilesets)).map((k) => `  ${JSON.stringify(k)}: ${tilesets[k]}`).join(',\n')}\n}\n\n` +
  `export const HW2_ENVIRONMENTS: readonly string[] = ${list(envs)}\n\n` +
  '/** Sample names in `res/assets/sound/music.bank` (FSB5, Vorbis): one per track. */\n' +
  `export const HW2_MUSIC: readonly string[] = ${list(music)}\n`

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (cur !== body) {
    console.error('hw2Assets.generated.ts is stale — run node scripts/scan-hw2-assets.mjs')
    process.exit(1)
  }
  console.log('hw2Assets.generated.ts is current')
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, body)
  console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${units.size} units, ${Object.keys(tilesets).length} tilesets, ${envs.length} envs, ${music.length} music samples`)
}
