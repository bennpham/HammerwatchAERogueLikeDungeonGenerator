#!/usr/bin/env node
// Snapshot the AE asset paths the generator may emit, so that tests (and the
// validator) can prove every path a generated level references exists in the
// game — without the game installed.
//
//   node scripts/scan-ae-assets.mjs            # rewrite src/generator/catalog/aeAssets.generated.ts
//   node scripts/scan-ae-assets.mjs --check    # exit 1 if the snapshot is stale
//
// Scope: every actor/item unit; the doodad folders the generator uses (walls'
// structural pieces, doors, generic, traps, special, lamps); every tileset
// with its tile size; every lighting environment. Set HWAE_ROOT to point at
// another install.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { findAeAssets } from './lib/aeunit.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const outFile = path.join(here, '..', 'src', 'generator', 'catalog', 'aeAssets.generated.ts')
const { assets } = findAeAssets()
if (!assets) {
  console.error('AE unpacked assets not found; set HWAE_ROOT')
  process.exit(1)
}

function walk(rel, out = []) {
  const abs = path.join(assets, rel)
  if (!fs.existsSync(abs)) return out
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const r = rel === '' ? e.name : `${rel}/${e.name}`
    if (e.isDirectory()) walk(r, out)
    else out.push(r)
  }
  return out
}

const WALL_PIECE = /^(h|h_16|h_32|h_single|single|v|v_16|v_32|crn_n[ew]|crn_s[ew]|x_[nsewx]|cap_h_[ew]|cap_v_[ns]|cap_[nsew]|exit_up|exit_dn|__color_\d+|__color_dither_\d+)\.unit$/
const units = new Set()
for (const f of walk('actors')) if (f.endsWith('.unit')) units.add(f)
for (const f of walk('items')) if (f.endsWith('.unit')) units.add(f)
for (const dir of ['doodads/doors', 'doodads/generic', 'doodads/traps', 'doodads/special', 'doodads/lamps', 'doodads/ledges']) {
  for (const f of walk(dir)) if (f.endsWith('.unit')) units.add(f)
}
for (const f of walk('doodads/walls')) {
  const parts = f.split('/')
  if (parts.length === 4 && WALL_PIECE.test(parts[3])) units.add(f)
}

const tilesets = {}
for (const f of walk('tilesets')) {
  if (!f.endsWith('.tileset')) continue
  const m = /<tileset[^>]*\bsize="(\d+)"/.exec(fs.readFileSync(path.join(assets, f), 'utf8'))
  tilesets[f] = m ? Number(m[1]) : 16
}
const envs = walk('effects').filter((f) => f.endsWith('.env'))
const prefabs = walk('prefabs').filter((f) => f.endsWith('.pfb'))

const sorted = (xs) => [...xs].sort()
const body =
  '// GENERATED by scripts/scan-ae-assets.mjs from a Hammerwatch Anniversary Edition\n' +
  `// install (${path.basename(assets)}). Do not edit by hand — rerun the script.\n` +
  '// Every asset path the generator emits must appear here (tests enforce it).\n\n' +
  `export const AE_ASSETS_SOURCE = ${JSON.stringify(path.basename(assets))}\n\n` +
  `export const AE_UNITS: readonly string[] = ${JSON.stringify(sorted(units), null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')}\n\n` +
  `export const AE_TILESET_SIZES: Readonly<Record<string, number>> = {\n${sorted(Object.keys(tilesets)).map((k) => `  ${JSON.stringify(k)}: ${tilesets[k]}`).join(',\n')}\n}\n\n` +
  `export const AE_ENVIRONMENTS: readonly string[] = ${JSON.stringify(sorted(envs), null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')}\n\n` +
  `export const AE_PREFABS: readonly string[] = ${JSON.stringify(sorted(prefabs), null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')}\n`

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (cur !== body) {
    console.error('aeAssets.generated.ts is stale — run node scripts/scan-ae-assets.mjs')
    process.exit(1)
  }
  console.log('aeAssets.generated.ts is current')
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, body)
  console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${units.size} units, ${Object.keys(tilesets).length} tilesets, ${envs.length} envs, ${prefabs.length} prefabs`)
}
