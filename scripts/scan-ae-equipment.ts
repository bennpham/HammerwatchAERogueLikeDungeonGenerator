// Snapshot AE's equipment — the item vendor's loot tables and every item by
// quality, with English names and effects — into
// src/generator/catalog/equipment.generated.ts, so the Lobby and Dungeon tabs
// can say what an item stall sells without the game installed.
//
//   node scripts/run-ts.mjs scripts/scan-ae-equipment.ts           # rewrite
//   node scripts/run-ts.mjs scripts/scan-ae-equipment.ts --check   # exit 1 if stale
//
// Set HWAE_ROOT to point at another install.
import fs from 'node:fs'
import path from 'node:path'
import {
  EQUIPMENT_QUALITIES,
  EQUIPMENT_TIER_IDS,
  parseEquipmentItems,
  parseEquipmentTiers,
  parseLang
} from '../src/generator/catalog/equipmentParse'

const root = process.env.HWAE_ROOT ?? 'D:/Program Files (x86)/Steam/steamapps/common/Hammerwatch Anniversary Edition'
const dirs = fs.existsSync(root) ? fs.readdirSync(root).filter((d) => /^unpacked_assets_\d+$/.test(d)) : []
dirs.sort((a, b) => Number(b.split('_').pop()) - Number(a.split('_').pop()))
if (dirs.length === 0) {
  console.error('AE unpacked assets not found; set HWAE_ROOT')
  process.exit(1)
}
const assets = path.join(root, dirs[0])
const read = (rel: string): string => fs.readFileSync(path.join(assets, rel), 'utf8')

const strings = parseLang(fs.readFileSync(path.join(root, 'res', 'language', 'english', 'items.lang'), 'utf8'))
const tiers = parseEquipmentTiers(read('tweak/shops/equipment.sval'))
const items = EQUIPMENT_QUALITIES.flatMap((q) => parseEquipmentItems(read(`tweak/items/${q}.sval`), strings))

const body = [
  '// GENERATED by scripts/scan-ae-equipment.ts from a Hammerwatch Anniversary Edition',
  `// install (${dirs[0]}). Do not edit by hand — rerun the script.`,
  '',
  "import type { EquipmentItem, EquipmentSlot } from './equipmentParse'",
  '',
  `export const EQUIPMENT_SOURCE = ${JSON.stringify(dirs[0])}`,
  '',
  '/** tweak/shops/equipment.sval: each table is a list of slots, one item per slot */',
  'export const EQUIPMENT_TIERS: Readonly<Record<string, readonly EquipmentSlot[]>> = {',
  ...EQUIPMENT_TIER_IDS.map((id) => `  ${id}: ${JSON.stringify(tiers[id] ?? [])},`),
  '}',
  '',
  '/** tweak/items/*.sval, in quality order */',
  'export const EQUIPMENT_ITEMS: readonly EquipmentItem[] = [',
  ...items.map((i) => `  ${JSON.stringify(i)},`),
  ']',
  ''
].join('\n')

const outFile = path.join(process.cwd(), 'src', 'generator', 'catalog', 'equipment.generated.ts')
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (current !== body) {
    console.error('equipment.generated.ts is stale; rerun scripts/scan-ae-equipment.ts')
    process.exit(1)
  }
  console.log('equipment snapshot is current')
} else {
  fs.writeFileSync(outFile, body)
  console.log(`${EQUIPMENT_TIER_IDS.length} tiers, ${items.length} items → ${path.relative(process.cwd(), outFile)}`)
}
