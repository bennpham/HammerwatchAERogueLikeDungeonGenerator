#!/usr/bin/env node
// Snapshot what Anniversary Edition's runtime knows by NAME, for copying
// another game's units into a scenario (experimental "Load custom"):
//
//   - AE_SCRIPT_CLASSES: every class AE's scripts declare. A copied unit whose
//     behavior or skill names a class AE lacks can't run (scripts are global;
//     a scenario can't rename them). docs/discovery/hammerwatch-2-assets.md
//   - AE_SOUND_EVENTS: every FMOD event AE's own assets name. AE's banks are
//     compressed, so the events its files reference stand in for the events its
//     banks hold; a copied unit's sound outside this list is blanked.
//
//   node scripts/scan-ae-runtime.mjs            # rewrite src/main/custom/aeRuntime.generated.ts
//   node scripts/scan-ae-runtime.mjs --check    # exit 1 if the snapshot is stale
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { findAeAssets } from './lib/aeunit.mjs'

const here = path.dirname(fileURLToPath(import.meta.url))
const outFile = path.join(here, '..', 'src', 'main', 'custom', 'aeRuntime.generated.ts')
const { assets } = findAeAssets()
if (!assets) {
  console.error('AE unpacked assets not found; set HWAE_ROOT')
  process.exit(1)
}

function walk(rel, out = []) {
  const abs = path.join(assets, rel)
  if (!fs.existsSync(abs)) return out
  for (const e of fs.readdirSync(abs, { withFileTypes: true })) {
    const r = rel === '' ? e.name : `${rel}/${e.name}`
    if (e.isDirectory()) walk(r, out)
    else out.push(r)
  }
  return out
}

const classes = new Set()
for (const f of walk('scripts')) {
  if (!f.endsWith('.as')) continue
  const t = fs.readFileSync(path.join(assets, f), 'utf8')
  for (const m of t.matchAll(/^\s*(?:shared\s+|abstract\s+|mixin\s+)*class\s+(\w+)/gm)) classes.add(m[1])
}

const events = new Set()
for (const top of ['actors', 'doodads', 'items', 'effects', 'players', 'scripts', 'levels', 'prefabs', 'special', 'tweak', 'gui']) {
  for (const f of walk(top)) {
    if (!/\.(unit|inc|effect|sval|as|lvl|pfb|gui)$/.test(f)) continue
    for (const m of fs.readFileSync(path.join(assets, f), 'latin1').matchAll(/event:\/[\w/\-.]+/g)) events.add(m[0])
  }
}

const list = (xs) => JSON.stringify([...xs].sort(), null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '"\n]')
const body =
  '// GENERATED by scripts/scan-ae-runtime.mjs from a Hammerwatch Anniversary Edition\n' +
  `// install (${path.basename(assets)}). Do not edit by hand — rerun the script.\n\n` +
  '/** Every class AE\'s scripts declare. */\n' +
  `export const AE_SCRIPT_CLASSES: readonly string[] = ${list(classes)}\n\n` +
  '/** Every FMOD event AE\'s own assets name. */\n' +
  `export const AE_SOUND_EVENTS: readonly string[] = ${list(events)}\n`

if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (cur !== body) {
    console.error('aeRuntime.generated.ts is stale — run node scripts/scan-ae-runtime.mjs')
    process.exit(1)
  }
  console.log('aeRuntime.generated.ts is current')
} else {
  fs.mkdirSync(path.dirname(outFile), { recursive: true })
  fs.writeFileSync(outFile, body)
  console.log(`wrote ${path.relative(process.cwd(), outFile)}: ${classes.size} classes, ${events.size} sound events`)
}
