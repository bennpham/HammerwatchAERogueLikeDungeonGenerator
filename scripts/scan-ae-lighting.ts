// Snapshot the ambient lines of every lighting environment a theme or a world biome uses into
// src/generator/lighting/envs.generated.ts, so the brightness setting can
// name the lines to patch without the game installed.
//
//   node scripts/run-ts.mjs scripts/scan-ae-lighting.ts           # rewrite
//   node scripts/run-ts.mjs scripts/scan-ae-lighting.ts --check   # exit 1 if stale
//
// Set HWAE_ROOT to point at another install.
import fs from 'node:fs'
import path from 'node:path'
import { THEME_DEFS } from '../src/generator/config/themes'
import { BIOME_DEFS } from '../src/generator/world/biomes'
import type { EnvSnapshot } from '../src/generator/lighting/envs'

const root = process.env.HWAE_ROOT ?? 'D:/Program Files (x86)/Steam/steamapps/common/Hammerwatch Anniversary Edition'
const dirs = fs.existsSync(root) ? fs.readdirSync(root).filter((d) => /^unpacked_assets_\d+$/.test(d)) : []
dirs.sort((a, b) => Number(b.split('_').pop()) - Number(a.split('_').pop()))
if (dirs.length === 0) {
  console.error('AE unpacked assets not found; set HWAE_ROOT')
  process.exit(1)
}
const assets = path.join(root, dirs[0])

const paths = [...new Set([...THEME_DEFS.flatMap((t) => t.environments), ...BIOME_DEFS.map((b) => b.environment)])].sort()
const envs: EnvSnapshot[] = []
for (const p of paths) {
  const file = path.join(assets, p)
  if (!fs.existsSync(file)) {
    console.error(`missing ${p}`)
    process.exit(1)
  }
  const ambients: EnvSnapshot['ambients'] = []
  fs.readFileSync(file, 'utf8')
    .split('\n')
    .forEach((line, i) => {
      const m = /<ambient value="([^"]*)"/.exec(line)
      if (m === null) return
      const value = m[1].trim().split(/\s+/).map(Number)
      ambients.push({ line: i + 1, text: m[1], value })
    })
  envs.push({ path: p, ambients })
}

const body = [
  '// GENERATED by scripts/scan-ae-lighting.ts from a Hammerwatch Anniversary Edition',
  `// install (${dirs[0]}). Do not edit by hand — rerun the script.`,
  '',
  "import type { EnvSnapshot } from './envs'",
  '',
  'export const ENV_SNAPSHOT: readonly EnvSnapshot[] = [',
  ...envs.map((e) => `  ${JSON.stringify(e)},`),
  ']',
  ''
].join('\n')

const outFile = path.join(process.cwd(), 'src', 'generator', 'lighting', 'envs.generated.ts')
if (process.argv.includes('--check')) {
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : ''
  if (current !== body) {
    console.error('envs.generated.ts is stale; rerun scripts/scan-ae-lighting.ts')
    process.exit(1)
  }
  console.log('lighting snapshot is current')
} else {
  fs.writeFileSync(outFile, body)
  console.log(`${envs.length} environments → ${path.relative(process.cwd(), outFile)}`)
}
