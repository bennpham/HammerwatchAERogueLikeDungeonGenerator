/**
 * Add (or replace, by id) one lobby template in
 * src/generator/lobby/templates.generated.ts, keeping every other template.
 * Shared by scripts/import-ae-lobby.mjs (hand-made editor levels) and
 * scripts/import-stock-towns.ts (the cleaned stock towns; it passes the
 * repo root, as run-ts bundles it away from this folder).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

export const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..')
export const TEMPLATES_REL = 'src/generator/lobby/templates.generated.ts'

/**
 * @param {{ id: string, label: string, description: string, lvl: string, redBeforeFight?: boolean }} template
 * @returns {number} how many templates the file now holds
 */
export function writeLobbyTemplate(template, root = ROOT) {
  const file = path.join(root, TEMPLATES_REL)
  const existing = []
  if (fs.existsSync(file)) {
    const m = /export const LOBBY_TEMPLATES[^=]*=\s*(\[[\s\S]*\])\s*$/m.exec(fs.readFileSync(file, 'utf8'))
    if (m !== null) existing.push(...JSON.parse(m[1]).filter((t) => t.id !== template.id))
  }
  const templates = [...existing, template].sort((a, b) => (a.id < b.id ? -1 : 1))

  fs.writeFileSync(
    file,
    `// Generated by scripts/import-ae-lobby.mjs and scripts/import-stock-towns.ts — do not edit by hand.
// Each entry is an AE level used as a lobby template: a hand-made editor level,
// or a stock one cleaned for the purpose.

export interface LobbyTemplate {
  id: string
  label: string
  description: string
  /** the level text, verbatim */
  lvl: string
  /** the room's teleporter turns red when a fight follows the lobby */
  redBeforeFight?: boolean
}

export const LOBBY_TEMPLATES: readonly LobbyTemplate[] = ${JSON.stringify(templates, null, 2)}
`
  )
  return templates.length
}
